"""Module interfaces (doc 02 §8).  Procedures depend on these Protocols only;
concrete backends are chosen in `diag_agent.app` (the composition root)."""

from __future__ import annotations

from typing import Any, Iterable, Protocol, runtime_checkable


@runtime_checkable
class SemanticMemory(Protocol):
    kb_release: str
    topology_id: str

    def sparql(self, query: str, bindings: dict[str, Any] | None = None) -> list[dict[str, Any]]: ...
    def walk(self, pattern: str, anchor: str) -> list[str]: ...
    def walk_reverse(self, pattern: str, target: str) -> list[str]: ...
    def documented_modes(self, resource: str) -> list[str]: ...
    def mode(self, mode_id: str) -> dict: ...
    def modes(self) -> dict[str, dict]: ...
    def cascade_rules(self) -> list[dict]: ...
    def location_terms(self) -> dict[str, dict]: ...
    def resolve_location(self, term: str, anchor: str) -> list[str]: ...
    def alarm_type(self, name: str) -> dict: ...
    def rules(self) -> list[dict]: ...
    def checks(self) -> dict[str, dict]: ...
    def resource(self, yang_id: str) -> dict: ...
    def classes_of(self, yang_id: str) -> set[str]: ...
    def is_a(self, yang_id: str, cls: str) -> bool: ...
    def cond_subsumes(self, general: str, specific: str) -> bool: ...
    def layer(self, key: str) -> dict: ...
    def neighbors(self, yang_id: str, limit: int = 30) -> list[dict]: ...
    def depends_on(self, yang_id: str) -> set[str]: ...
    def publish(self, graph_name: str, triples_ttl: str, meta: dict) -> None: ...


@runtime_checkable
class EpisodicMemory(Protocol):
    def retrieve(self, role_signature: dict, k: int = 20) -> list[tuple[dict, float]]: ...
    def write_episode(self, episode: dict) -> str: ...
    def add_followup(self, episode_id: str, kind: str, payload: dict) -> None: ...
    def count(self) -> int: ...


@runtime_checkable
class Substrate(Protocol):
    incident_id: int
    created_at: str

    def alarms_until(self, t_s: float) -> list[dict]: ...
    def first_alarm_time(self) -> float | None: ...
    def ppe_trace(self, och: str, t_s: float) -> dict | None: ...
    def ppe_traces_until(self, t_s: float) -> list[dict]: ...
    def audit(self, *, ne: str | None = None, port: str | None = None, t_s: float) -> list[dict]: ...
    def access_log(self) -> list[dict]: ...


@runtime_checkable
class CheckExecutor(Protocol):
    def run(self, check_id: str, target: str, t_s: float) -> dict: ...


@runtime_checkable
class FieldAnswerer(Protocol):
    def answer(self, check_id: str, target: str) -> dict: ...


@runtime_checkable
class LLMProvider(Protocol):
    profile_name: str
    model: str

    def available(self, role: str) -> bool: ...
    def chat(self, role: str, messages: list[dict], *, tools: list[dict] | None = None,
             json_mode: bool = False) -> dict: ...


@runtime_checkable
class Notifier(Protocol):
    def on_raise(self, view: dict) -> dict: ...
    def on_update(self, view: dict) -> dict: ...
    def on_task(self, incident_no: str, task: dict) -> None: ...
    def on_clear(self, incident_no: str, t_iso: str) -> None: ...
    def tree_delta(self, incident_no: str, nodes: Iterable[dict]) -> None: ...


@runtime_checkable
class Clock(Protocol):
    def now(self) -> float: ...
    def advance_to(self, t_s: float) -> float: ...
