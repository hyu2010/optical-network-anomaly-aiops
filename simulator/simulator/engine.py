"""Cascade expansion (L1 + L2) and suppression filtering.

Three pipeline stages operate on the *seed* alarm list each fault rule produces:

  L1 (suppression-graph forward walk)
      For every seed, traverse the curated edges in
      `data/alarm_suppression.json` forward and add every reachable alarm
      at the same NE/board/port/container.

  L2 (cause-keyword index)
      Read every alarm's parsed "Possible Causes" text once
      (`data/alarms_detail.json`), index by keyword group, and for each
      fault add every alarm whose causes match the fault's declared
      keyword set.

  Suppression filter
      For each alarm, if any of its transitive upstreams in the
      suppression graph is also present, drop it from the operator-facing
      view.  Both raw and suppressed views are returned.

The published suppression edges use rate-suffixed names (`OTUk_SSF`); we
strip the suffix so they line up with the family-form names emitted by
the fault rules (`OTU_SSF`).
"""
from __future__ import annotations

import json
import os
import re
from collections import defaultdict

from .faults import Alarm, severity_of

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SUPPRESSION_FILE = os.path.join(ROOT, "data", "alarm_suppression.json")
ALARM_DETAIL_FILE = os.path.join(ROOT, "data", "alarms_detail.json")


# ---------------------------------------------------------------------------
# Name normalisation: OTUk_SSF / OTU2_SSF / OTU3_SSF -> OTU_SSF
# ---------------------------------------------------------------------------

_RATE_RE = re.compile(r"^([A-Z]+)([0-9]+G?|k)(_.+)?$")
# Only these family prefixes carry an OTN rate suffix (OTUk, ODUk, OPUk, etc.)
# B1/B2/B3 are SDH byte names — strip would produce a non-existent `B_EXC`.
_RATE_FAMILIES = {"OTU", "ODU", "OPU"}


def normalise(name: str) -> str:
    m = _RATE_RE.match(name)
    if not m:
        return name
    prefix = m.group(1)
    if prefix not in _RATE_FAMILIES:
        return name
    suffix = m.group(3) or ""
    return prefix + suffix


# ---------------------------------------------------------------------------
# Suppression graph
# ---------------------------------------------------------------------------

def _load_edges() -> dict[str, set[str]]:
    """upstream -> {downstreams}  (after rate-suffix normalisation)."""
    out: dict[str, set[str]] = {}
    raw = json.load(open(SUPPRESSION_FILE, encoding="utf-8"))
    for u, d in raw:
        out.setdefault(normalise(u), set()).add(normalise(d))
    return out


_EDGES_CACHE: dict[str, set[str]] | None = None


def edges() -> dict[str, set[str]]:
    global _EDGES_CACHE
    if _EDGES_CACHE is None:
        _EDGES_CACHE = _load_edges()
    return _EDGES_CACHE


_FORWARD_CACHE: dict[str, frozenset[str]] = {}


def forward_walk(name: str) -> frozenset[str]:
    """Transitive set of alarm names that fire downstream of `name`.

    Includes `name` itself in the returned set so callers don't have to
    handle the seed specially.
    """
    if name in _FORWARD_CACHE:
        return _FORWARD_CACHE[name]
    seen: set[str] = {name}
    stack: list[str] = [name]
    g = edges()
    while stack:
        cur = stack.pop()
        for nxt in g.get(cur, ()):
            if nxt not in seen:
                seen.add(nxt)
                stack.append(nxt)
    fs = frozenset(seen)
    _FORWARD_CACHE[name] = fs
    return fs


_UP_CACHE: dict[str, frozenset[str]] = {}


def upstreams(name: str) -> frozenset[str]:
    """Transitive upstreams of `name` in the suppression graph (excluding `name`)."""
    if name in _UP_CACHE:
        return _UP_CACHE[name]
    seen: set[str] = set()
    g = edges()
    # build inverse adjacency on the fly
    stack: list[str] = []
    for u, ds in g.items():
        if name in ds:
            stack.append(u)
    while stack:
        cur = stack.pop()
        if cur in seen:
            continue
        seen.add(cur)
        for u, ds in g.items():
            if cur in ds and u not in seen:
                stack.append(u)
    fs = frozenset(seen)
    _UP_CACHE[name] = fs
    return fs


# ---------------------------------------------------------------------------
# Layer inference (used for new alarms generated by L1/L2)
# ---------------------------------------------------------------------------

def layer_of(name: str) -> str:
    if name.startswith("OTS"):
        return "OTS"
    if name.startswith("OMS"):
        return "OMS"
    if name.startswith("OCh") or name.startswith("OCH"):
        return "OCH"
    if name.startswith("OTU"):
        return "OTU"
    if name.startswith(("ODU", "OPU")):
        return "ODU"
    if name.startswith(("MS_", "AU_", "HP_", "LP_", "B1_", "B2_", "B3_")):
        return "SDH"
    if name.startswith(("R_LOS", "R_LOF", "MUT_LOS", "CHAN_LOS")):
        return "OTS"
    if name.startswith(("ALS_", "LSR_", "LASER_", "ALM_ALS")):
        return "equipment"
    if name.startswith(("IN_PWR", "OUT_PWR")):
        return "OTS"
    if name.startswith(("FEC", "BEFFEC")):
        return "OTU"
    if name.startswith(("FAN_", "TEMP_", "AMBIENT_", "PUMP_COOL")):
        return "environment"
    if name.startswith(("POWER_", "PWR_", "VOLT")):
        return "equipment"
    if name.startswith(("BD_", "HARD_", "BUS_", "FW_BD", "WRG_BD")):
        return "equipment"
    if name.startswith(("ETH_", "GFP_", "LINK_", "FC_", "GE_")):
        return "client"
    if name.startswith(("APS_", "TPS_", "DLAG", "OLP_", "SNCP", "PROTECT", "PROTOCOL")):
        return "protection"
    if name.startswith(("ALC_", "APE_", "IPA_", "OPA_")):
        return "auto-power"
    if name.startswith(("CLK", "CLOCK", "SYNC")):
        return "clock"
    if name.startswith(("COMMUN_", "ECC_", "NE_OFFLINE", "DCN")):
        return "management"
    return "other"


# ---------------------------------------------------------------------------
# L1: forward-walk every seed and add reachable alarms at the same location
# ---------------------------------------------------------------------------

def expand_l1(seeds: list[Alarm], hop_delay_ms: int = 5) -> list[Alarm]:
    """For each seed, generate Alarm objects for every transitive forward-reachable
    alarm name, attached to the seed's NE/board/port/container.  Returns a NEW
    list with seeds first, then their L1-derived children.  De-dupes by
    (name, ne, board, port).
    """
    out: list[Alarm] = []
    seen: set[tuple[str, str, str, str]] = set()
    for s in seeds:
        for a in (s, *(_l1_children_of(s, hop_delay_ms))):
            key = (a.name, a.ne, a.board, a.port)
            if key in seen:
                continue
            seen.add(key)
            out.append(a)
    return out


def _l1_children_of(seed: Alarm, hop_delay_ms: int) -> list[Alarm]:
    children: list[Alarm] = []
    for i, child_name in enumerate(forward_walk(seed.name)):
        if child_name == seed.name:
            continue
        children.append(Alarm(
            name=child_name,
            layer=layer_of(child_name),
            ne=seed.ne,
            board=seed.board,
            port=seed.port,
            container_id=seed.container_id,
            severity=severity_of(child_name),
            t_offset_ms=seed.t_offset_ms + (i + 1) * hop_delay_ms,
            is_root=False,
        ))
    return children


# ---------------------------------------------------------------------------
# L2: cause-keyword index
# ---------------------------------------------------------------------------

# Conservative regexes — narrow and physical, to avoid over-firing.
_KW_PATTERNS: dict[str, re.Pattern] = {
    "fiber":         re.compile(r"\b(fiber|cable|connector|fiber cut|line performance|cut)\b", re.I),
    "los":           re.compile(r"\b(LOS|loss of signal|loss of light|signal lost|signal failure|loss of frame)\b", re.I),
    "laser":         re.compile(r"\b(laser|optical module|XFP|SFP|transmit (?:end|side))\b", re.I),
    "optical_power": re.compile(r"\b(optical power|input power|output power|attenuation|insertion loss)\b", re.I),
    "power_supply":  re.compile(r"\b(power supply|power source|power input|-48v|pem|voltage)\b", re.I),
    "temp":          re.compile(r"\b(temperature|cooling|fan|over.?temp|heat)\b", re.I),
    "biterr":        re.compile(r"\b(bit error|B1\b|B2\b|FEC|degrade|excessive errors|errors over)\b", re.I),
    "config":        re.compile(r"\b(configuration|misconfigured|mismatch|inconsistent|wrong|invalid setting|trail|TIM|PLM)\b", re.I),
}


_KEYWORD_INDEX_CACHE: dict[str, set[str]] | None = None


def keyword_index() -> dict[str, set[str]]:
    """{keyword -> set of alarm-name family-forms whose Possible Causes match}."""
    global _KEYWORD_INDEX_CACHE
    if _KEYWORD_INDEX_CACHE is not None:
        return _KEYWORD_INDEX_CACHE
    out: dict[str, set[str]] = {kw: set() for kw in _KW_PATTERNS}
    raw = json.load(open(ALARM_DETAIL_FILE, encoding="utf-8"))
    for key, entry in raw.items():
        causes = entry.get("possible_causes", [])
        if not causes:
            continue
        text = " ".join(causes)
        # entry key is "NAME" or "NAME::variant"; we want the family-form name
        family_name = normalise(key.split("::", 1)[0])
        for kw, pat in _KW_PATTERNS.items():
            if pat.search(text):
                out[kw].add(family_name)
    _KEYWORD_INDEX_CACHE = out
    return out


def expand_l2(seeds: list[Alarm], keywords: set[str],
              base_alarm: Alarm | None = None,
              t_offset_start_ms: int = 50) -> list[Alarm]:
    """Look up every alarm name whose causes match any of `keywords` and emit
    Alarm objects at `base_alarm`'s location (or the first seed's location if
    `base_alarm` is None).  Returns a NEW list of L2-only alarms (does not
    include the seeds themselves; caller concatenates).
    """
    if not keywords or not seeds:
        return []
    base = base_alarm or seeds[0]
    seen: set[tuple[str, str, str, str]] = {(s.name, s.ne, s.board, s.port) for s in seeds}
    idx = keyword_index()
    matched: set[str] = set()
    for kw in keywords:
        matched |= idx.get(kw, set())

    out: list[Alarm] = []
    for i, name in enumerate(sorted(matched)):
        key = (name, base.ne, base.board, base.port)
        if key in seen:
            continue
        seen.add(key)
        out.append(Alarm(
            name=name,
            layer=layer_of(name),
            ne=base.ne,
            board=base.board,
            port=base.port,
            container_id=base.container_id,
            severity=severity_of(name),
            t_offset_ms=t_offset_start_ms + i,   # +1 ms each so order is stable
            is_root=False,
        ))
    return out


# ---------------------------------------------------------------------------
# Top-level expansion
# ---------------------------------------------------------------------------

def expand_cascade(seeds: list[Alarm], keywords: set[str] | None = None,
                   group_id: str = "R1") -> list[Alarm]:
    """Take fault-rule seeds, run L1 (forward suppression-walk on every seed)
    then L2 (cause-keyword expansion at the first seed's location), and
    return the de-duplicated raw cascade.

    Every emitted alarm is tagged with `group_id` so that downstream consumers
    can distinguish derived alarms from different roots in compound incidents.
    """
    after_l1 = expand_l1(seeds)
    after_l2 = expand_l2(after_l1, keywords or set())
    cascade = after_l1 + after_l2
    if group_id:
        for a in cascade:
            a.group_id = group_id
    return cascade


# ---------------------------------------------------------------------------
# Polling-delay model: derive an NMS-observed time from physical propagation
# ---------------------------------------------------------------------------
#
# Real NMSes don't see an alarm the instant the underlying physical event
# happens — they poll each layer/board on its own timer.  Optical-section
# polling is on the order of a few seconds; environmental polling can be
# minutes.  We model this by adding, per alarm, a uniform [0, cadence)
# delay to the physical t_offset_ms to derive t_observed_ms.  Each alarm is
# jittered independently, so observation order does NOT have to match
# propagation order — preventing an ML model from cheating on root-cause
# identification by sorting on timestamp.

POLL_CADENCE_MS: dict[str, int] = {
    "OTS":         5_000,    # optical-section: fast
    "OMS":         5_000,
    "OCH":        10_000,
    "OTU":        30_000,
    "ODU":        60_000,
    "SDH":        30_000,
    "FEC":        60_000,
    "client":     60_000,
    "protection": 60_000,
    "auto-power": 60_000,
    "clock":      60_000,
    "management": 60_000,
    "equipment": 120_000,    # board state, power: every ~2 min
    "environment": 300_000,  # temp / fan: every ~5 min
}
DEFAULT_POLL_MS = 60_000


def apply_polling_delay(cascade: list[Alarm], rng=None) -> list[Alarm]:
    """For each alarm, derive `t_observed_ms = t_offset_ms + uniform(0, cadence)`
    where `cadence` is set by the alarm's layer.  Returns a NEW list of
    Alarms, sorted by `t_observed_ms`.  Mutates nothing.

    Pass an `rng` (e.g. `random.Random(seed)`) for reproducibility; defaults
    to the global `random` module otherwise.
    """
    import random
    rng = rng or random
    out: list[Alarm] = []
    for a in cascade:
        cadence = POLL_CADENCE_MS.get(a.layer, DEFAULT_POLL_MS)
        observed = a.t_offset_ms + rng.randint(0, cadence)
        out.append(Alarm(
            name=a.name, layer=a.layer,
            ne=a.ne, board=a.board, port=a.port,
            container_id=a.container_id,
            severity=a.severity,
            t_offset_ms=a.t_offset_ms,
            is_root=a.is_root,
            t_observed_ms=observed,
            group_id=a.group_id,
        ))
    out.sort(key=lambda a: a.t_observed_ms)
    return out


# ---------------------------------------------------------------------------
# Suppression filter
# ---------------------------------------------------------------------------

def apply_suppression(cascade: list[Alarm]) -> list[Alarm]:
    """Drop every alarm whose any-upstream in the suppression graph is also
    present in the cascade.  Same-named instances at different locations are
    treated independently (we look up upstreams by name, but presence by name
    too — at this layer of abstraction that's the right granularity).
    """
    present = {a.name for a in cascade}
    kept: list[Alarm] = []
    for a in cascade:
        if upstreams(a.name) & present:
            continue
        kept.append(a)
    return kept


# ---------------------------------------------------------------------------
# PPE expansion — paired with the alarm-side `expand_cascade` (Design/12 §6.3)
# ---------------------------------------------------------------------------

def expand_ppe(t, fault_type: str, *args,
               rng=None, group_id: str = "R1", **kwargs):
    """Generate PPE traces for a fault and append the detector's view to each.

    Returns `list[ppe.PpeTrace]`.  Each trace's `anomalies` list carries:
      * the emitter-planted ground truth (`is_root=True`), and
      * the deterministic detector's findings (`is_root=False`)
    so downstream consumers can train against either or both views.

    Polling jitter (`ppe.apply_polling_delay`) is NOT applied here — the
    caller is expected to chain it the same way `engine.apply_polling_delay`
    is chained on the alarm side.
    """
    from . import ppe   # local import: ppe imports numpy, engine doesn't
    traces = ppe.generate(t, fault_type, *args,
                          rng=rng, group_id=group_id, **kwargs)
    for tr in traces:
        tr.anomalies.extend(ppe.detect_anomalies(tr))
    return traces
